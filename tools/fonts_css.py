def font_faces():
    """Όλα τα @font-face ως ένα string CSS."""
    out = []
    for weight, style, family, data in FACES:
        b64 = "".join(data.split())
        out.append(
            "@font-face{"
            f"font-family:'{family}';"
            f"font-style:{style};"
            f"font-weight:{weight};"
            f"src:url(data:font/woff2;base64,{b64}) format('woff2');"
            "}"
        )
    return "".join(out)


